"""No-provider demonstration of preregistration, paired analysis, and claim limits.

Every outcome is generated by a known synthetic distribution. This script does
not call Hermes or a model, and its statistics are NOT evidence of Hermes gains.
Run using the managed zhulong-python wrapper; stdlib only.
"""
import hashlib
import json
import math
import pathlib
import random
import sys

ROOT = pathlib.Path(sys.argv[1]).resolve()
ROOT.mkdir(parents=True, exist_ok=True)
PROTOCOL = {
    "schema": 1,
    "experiment_kind": "synthetic-analysis-demonstration",
    "provider_calls_allowed": 0,
    "unit": "independent synthetic task pair",
    "pairs": 384,
    "strata": [f"{domain}/{difficulty}" for domain in ("code", "data", "recovery")
               for difficulty in ("easy", "hard")],
    "pairs_per_stratum": 64,
    "primary": "paired difference in deadline-and-cleanup-verified success probability",
    "secondary": ["total tokens per allocated run", "tokens per verified success"],
    "alpha": 0.05,
    "fixed_sample": True,
    "bootstrap_draws": 2000,
    "data_seed": 20261011,
    "allocation_seed": 912640,
    "analysis_seed": 829001,
    "synthetic_beneficial_discordance_probability": 0.18,
    "synthetic_harmful_discordance_probability": 0.06,
    "claim_ceiling": "pipeline demonstration; no actual agent causal inference",
}

def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"), allow_nan=False)

def sha(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()

PROTOCOL_HASH = sha(PROTOCOL)

def generate():
    data_rng = random.Random(PROTOCOL['data_seed'])
    allocation_rng = random.Random(PROTOCOL['allocation_seed'])
    rows = []
    for stratum in PROTOCOL['strata']:
        p_baseline = 0.74 if stratum.endswith('easy') else 0.38
        for offset in range(PROTOCOL['pairs_per_stratum']):
            # Joint potential outcomes are known here only because this is a
            # simulator. It does NOT mean a model seed makes real outcomes paired.
            draw = data_rng.random()
            baseline_only = draw < 0.06
            treatment_only = 0.06 <= draw < 0.24
            both_success = 0.24 <= draw < 0.24 + (p_baseline - 0.06)
            baseline = baseline_only or both_success
            treatment = treatment_only or both_success
            tokens_baseline = 3000 + (1600 if stratum.endswith('hard') else 0) + data_rng.randrange(600)
            tokens_treatment = max(1, tokens_baseline - 350 + data_rng.randrange(-200, 201))
            task_input = {"synthetic_id": stratum + '/' + str(offset)}
            rows.append({
                "pair_id": stratum + '/' + str(offset),
                "stratum": stratum,
                "input_hash": sha(task_input),
                "protocol_hash": PROTOCOL_HASH,
                "order": "T,B" if allocation_rng.randrange(2) else "B,T",
                "source": "synthetic-generator-no-model",
                "baseline_success": int(baseline),
                "treatment_success": int(treatment),
                "baseline_total_tokens": tokens_baseline,
                "treatment_total_tokens": tokens_treatment,
            })
    return rows

def validate(rows):
    if len(rows) != PROTOCOL['pairs']:
        raise ValueError('missing_or_excess_allocated_pairs')
    seen = set()
    stratum_counts = dict.fromkeys(PROTOCOL['strata'], 0)
    for row in rows:
        if row['pair_id'] in seen:
            raise ValueError('duplicate_pair_id')
        seen.add(row['pair_id'])
        if row['protocol_hash'] != PROTOCOL_HASH:
            raise ValueError('protocol_hash_mismatch')
        if row['source'] != 'synthetic-generator-no-model':
            raise ValueError('incorrect_simulator_provenance')
        if sha({'synthetic_id': row['pair_id']}) != row['input_hash']:
            raise ValueError('input_hash_mismatch')
        if row['order'] not in ('B,T', 'T,B'):
            raise ValueError('invalid_randomized_order')
        for key in ('baseline_success', 'treatment_success'):
            if type(row[key]) is not int or row[key] not in (0, 1):
                raise ValueError('invalid_binary_outcome')
        stratum_counts[row['stratum']] += 1
    if set(stratum_counts.values()) != {PROTOCOL['pairs_per_stratum']}:
        raise ValueError('unregistered_stratum_allocation')

def paired_analysis(rows):
    validate(rows)
    n = len(rows)
    b_success = sum(r['baseline_success'] for r in rows)
    t_success = sum(r['treatment_success'] for r in rows)
    positive = sum(r['treatment_success'] == 1 and r['baseline_success'] == 0 for r in rows)
    negative = sum(r['treatment_success'] == 0 and r['baseline_success'] == 1 for r in rows)
    discordant = positive + negative
    # Exact two-sided conditional binomial/McNemar test under exchangeable
    # independent paired discordance. Not a correction for contamination.
    p_exact = min(1.0, 2 * sum(math.comb(discordant, k) for k in range(min(positive, negative) + 1)) / 2**discordant) if discordant else 1.0
    grouped = [[r['treatment_success'] - r['baseline_success']
                for r in rows if r['stratum'] == stratum] for stratum in PROTOCOL['strata']]
    rng = random.Random(PROTOCOL['analysis_seed'])
    bootstrap = []
    for _ in range(PROTOCOL['bootstrap_draws']):
        bootstrap.append(sum(sum(rng.choice(group) for _ in group) for group in grouped) / n)
    bootstrap.sort()
    alpha = PROTOCOL['alpha']
    lower_index = int((alpha / 2) * len(bootstrap))
    upper_index = min(len(bootstrap) - 1, int((1 - alpha / 2) * len(bootstrap)))
    difference = (t_success - b_success) / n
    # A conservative fixed-N bounded-variable interval: D is in [-1,1].
    # Valid under independent pairs, but not valid repeatedly inspected as a CS.
    radius = math.sqrt(2 * math.log(2 / alpha) / n)
    bt = sum(r['baseline_total_tokens'] for r in rows)
    tt = sum(r['treatment_total_tokens'] for r in rows)
    return {
        "evidence_grade": "E0_simulated_pipeline",
        "experiment_kind": PROTOCOL['experiment_kind'],
        "provider_calls": 0,
        "preregistration_hash": PROTOCOL_HASH,
        "outcomes_hash": sha(rows),
        "pairs": n,
        "baseline_successes": b_success,
        "treatment_successes": t_success,
        "absolute_gain_percentage_points": round(100 * difference, 4),
        "beneficial_discordant_pairs": positive,
        "harmful_discordant_pairs": negative,
        "paired_exact_null_p_value": p_exact,
        "approximate_stratified_percentile_bootstrap_95_interval_pp": [100 * bootstrap[lower_index], 100 * bootstrap[upper_index]],
        "conservative_fixed_N_hoeffding_95_interval_pp": [100 * max(-1, difference - radius), 100 * min(1, difference + radius)],
        "simulated_tokens_per_allocated_run": {"baseline": bt / n, "treatment": tt / n},
        "simulated_tokens_per_verified_success": {"baseline": bt / b_success if b_success else None, "treatment": tt / t_success if t_success else None},
        "claim_allowed": "Deterministic offline preregistration and analysis pipeline works on declared synthetic data.",
        "claim_forbidden": "This provides no evidence that Hermes, its skills, experience, self-model or consciousness improved.",
    }

def negative_checks(rows):
    checks = []
    cases = [('missing_pair', rows[:-1]), ('duplicate_pair', rows[:-1] + [rows[0]])]
    altered = [dict(row) for row in rows]
    altered[0]['protocol_hash'] = 'different-protocol'
    cases.append(('protocol_substitution', altered))
    altered = [dict(row) for row in rows]
    altered[0]['input_hash'] = 'different-input'
    cases.append(('input_substitution', altered))
    for name, candidate in cases:
        try:
            validate(candidate)
        except ValueError:
            checks.append(name)
        else:
            raise AssertionError('invalid fixture was accepted: ' + name)
    return checks

if __name__ == '__main__':
    rows = generate()
    result = paired_analysis(rows)
    result['negative_fixture_checks_passed'] = negative_checks(rows)
    assert rows == generate(), 'generation is not reproducible'
    assert result['preregistration_hash'] == sha(PROTOCOL)
    (ROOT / 'offline-protocol.json').write_text(json.dumps(PROTOCOL, ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'offline-outcomes.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'offline-analysis.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(result, ensure_ascii=False, indent=2))
